  t(key) {
    const lang = this.currentLang || 'en';
    return (this.translations[lang] && this.translations[lang][key]) || this.translations['en'][key] || key;
  },

  setLanguage(lang) {
    if (this.translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('esetu_lang', lang);
      if (window.renderApp) {
        window.renderApp();
      }
    }
  },

  // Text-To-Speech Audio Synthesis supporting all 7 languages
  speak(text, customLang) {
    if (!('speechSynthesis' in window)) {
      alert('Speech synthesis is not supported in this browser.');
      return;
    }
    window.speechSynthesis.cancel();

    const langMap = {
      en: 'en-IN',
      hi: 'hi-IN',
      mr: 'mr-IN',
      ta: 'ta-IN',
      te: 'te-IN',
      kn: 'kn-IN',
      ml: 'ml-IN'
    };

    const langCode = customLang || langMap[this.currentLang] || 'en-IN';
    const utterance = new SpeechSynthesisUtterance(text);
    utterance.lang = langCode;
    utterance.rate = 0.95;
    utterance.pitch = 1.0;

    const voices = window.speechSynthesis.getVoices();
    const voicePrefix = langCode.substring(0, 2);
    const matchedVoice = voices.find(v => v.lang.startsWith(voicePrefix) || v.lang.includes('IN'));
    if (matchedVoice) {
      utterance.voice = matchedVoice;
    }

    window.speechSynthesis.speak(utterance);
  }
